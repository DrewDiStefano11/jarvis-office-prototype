/**
 * Renders docs/sprites/SOURCE_ASSET_INVENTORY.md from the measured inventory.
 * Output is a pure function of the JSON, so regeneration is deterministic.
 *
 * Usage: node scripts/sprites/generate-inventory-doc.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..', '..');

const inventory = JSON.parse(readFileSync(
    join(REPO_ROOT, 'src', 'office', 'sprites', 'source-asset-inventory.json'), 'utf8'));
const productionMap = JSON.parse(readFileSync(
    join(REPO_ROOT, 'src', 'office', 'sprites', 'production-asset-map.json'), 'utf8'));

const destinationFor = source =>
    productionMap.mappings.find(m => m.source === source)?.destination ?? '—';

const yn = value => (value ? 'yes' : 'no');

function structureSummary(asset) {
    if (asset.nexusGrid) {
        const g = asset.nexusGrid;
        return `${g.detectedColumns} cols x ${g.detectedRows} rows = ${g.totalCells} cells, uniform: ${yn(g.uniformCells)}`;
    }
    if (asset.agentGrid) {
        const g = asset.agentGrid;
        return `${g.columns} cols x ${g.rows} rows = ${g.totalCells} cells @ ${g.assumedCellSize.width}x${g.assumedCellSize.height}, equal-cell valid: ${yn(g.equalCellExtractionValid)}`;
    }
    return 'no measurable cell structure';
}

function assetKind(asset) {
    if (asset.nexusGrid) return 'sprite sheet (non-uniform grid)';
    if (asset.agentGrid) {
        return asset.agentGrid.equalCellExtractionValid
            ? 'sprite sheet (uniform grid)'
            : 'sprite sheet (irregular / ambiguous)';
    }
    return 'concept / role reference sheet';
}

const lines = [];
lines.push('# Source Asset Inventory');
lines.push('');
lines.push('> Generated by `scripts/sprites/generate-inventory-doc.mjs` from');
lines.push('> `src/office/sprites/source-asset-inventory.json`. Do not edit by hand.');
lines.push('> Every value below is measured from pixel data, never inferred from a filename.');
lines.push('');
lines.push(`Total source assets: **${inventory.totalAssets}**  `);
lines.push(`Exact duplicate groups: **${inventory.duplicateGroups.length}**  `);
lines.push(`Ink alpha threshold used for bounds: **${inventory.inkAlphaThreshold}**`);
lines.push('');

lines.push('## Summary table');
lines.push('');
lines.push('| # | File | Dimensions | Depth/Type | Alpha | Transparency used | Classification | Readiness | Ambiguous |');
lines.push('|---|------|-----------|-----------|-------|-------------------|----------------|-----------|-----------|');
inventory.assets.forEach((a, i) => {
    lines.push(`| ${i} | \`${a.path}\` | ${a.width}x${a.height} | ${a.bitDepth}/${a.colorType} | ${yn(a.hasAlphaChannel)} | ${yn(a.transparencyUsed)} | ${a.classification} | ${a.readiness} | ${yn(a.ambiguous)} |`);
});
lines.push('');

lines.push('## Per-asset detail');
lines.push('');
for (const a of inventory.assets) {
    lines.push(`### \`${a.path}\``);
    lines.push('');
    lines.push(`- Repository path: \`${a.path}\``);
    lines.push(`- File size: ${a.fileSizeBytes.toLocaleString('en-US')} bytes`);
    lines.push(`- SHA-256: \`${a.sha256}\``);
    lines.push(`- Dimensions: ${a.width} x ${a.height}`);
    lines.push(`- PNG bit depth: ${a.bitDepth}`);
    lines.push(`- PNG colour type: ${a.colorType} (${a.channels} channel${a.channels === 1 ? '' : 's'})`);
    lines.push(`- PNG chunks: ${a.chunkTypes.map(c => `\`${c}\``).join(', ')}`);
    lines.push(`- True alpha channel: ${yn(a.hasAlphaChannel)}`);
    lines.push(`- Transparency actually used: ${yn(a.transparencyUsed)} (alpha range ${a.minAlpha}–${a.maxAlpha})`);
    lines.push(`- Fully transparent pixels: ${a.fullyTransparentPixels.toLocaleString('en-US')}`);
    lines.push(`- Partially transparent pixels: ${a.partiallyTransparentPixels.toLocaleString('en-US')}`);
    lines.push(`- Uniform opaque background: ${a.uniformOpaqueBackground ? `yes (${a.backgroundColor})` : 'no'}`);
    lines.push(`- Appears to be: ${assetKind(a)}`);
    lines.push(`- Measured structure: ${structureSummary(a)}`);
    if (a.agentGrid) {
        lines.push(`- Blank cells: ${a.agentGrid.blankCells}`);
        lines.push(`- Cells spilling horizontally past the cell boundary: ${a.agentGrid.horizontalSpillCells}`);
        lines.push(`- Measured ink column bands: ${a.agentGrid.detectedColumnBands}; row bands: ${a.agentGrid.detectedRowBands}`);
        lines.push(`- All cells equal size: ${yn(a.agentGrid.widthDivisible && a.agentGrid.heightDivisible)}`);
    }
    if (a.nexusGrid) {
        lines.push(`- Blank cells: ${a.nexusGrid.blankCells.length}`);
        lines.push(`- Distinct measured cell widths: ${a.nexusGrid.distinctCellWidths.join(', ')}`);
        lines.push(`- Distinct measured cell heights: ${a.nexusGrid.distinctCellHeights.join(', ')}`);
        lines.push(`- All cells equal size: ${yn(a.nexusGrid.uniformCells)}`);
    }
    lines.push(`- Classification: **${a.classification}**`);
    lines.push(`- Readiness: **${a.readiness}**`);
    lines.push(`- Ambiguous: ${yn(a.ambiguous)}`);
    lines.push(`- Public copy: \`public/${destinationFor(a.path)}\``);
    if (a.warnings.length > 0) {
        lines.push('- Warnings / unresolved questions:');
        for (const w of a.warnings) lines.push(`  - ${w}`);
    } else {
        lines.push('- Warnings: none');
    }
    lines.push('');
}

lines.push('## Notes on interpretation');
lines.push('');
lines.push('- Labels and numbers embedded in artwork were checked visually. `Sprite Jobs.png`');
lines.push('  contains printed numbers 1–30 and job titles baked into the image, which is one');
lines.push('  reason it is reference-only rather than an animation sheet.');
lines.push('- No character names, job assignments, facing directions or animation state names');
lines.push('  were invented. Where the source does not state something, it is recorded as');
lines.push('  unresolved rather than guessed.');
lines.push('');

const outDir = join(REPO_ROOT, 'docs', 'sprites');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'SOURCE_ASSET_INVENTORY.md'), `${lines.join('\n')}\n`);
process.stdout.write('Wrote docs/sprites/SOURCE_ASSET_INVENTORY.md\n');
